#!/usr/bin/env python3
"""Install the final-closure focused forecasts and recompute every consumer.

``audit/final_closure_local_runs.py`` produces, on macOS,

* 20 focused XGBoost runs (original focused search/final-fit protocol, with
  the corrected target-minute feature alignment), and
* one local CPU-mode LSTM run for ``MS_25320`` on the past-only input.

This script

1. verifies every run (``final_closure_local_runs.verify_run``: Darwin
   environment, input/split/trainer hashes, 200/15 complete trials,
   4 effective XGBoost folds with the expected boundaries, 4,320 held-out
   timestamps, artefact hashes);
2. preserves the pre-closure canonical forecast files and training logs once
   under ``experiments/results/superseded_2026-09-28_final_closure/`` and
   writes new canonical ``experiments/results/{xgb,lstm}_forecasts.parquet``
   (XGBoost: all 20 services from the new runs; LSTM: MS_25320 from the local
   run, the other 19 services byte-for-byte semantic copies) and
   ``xgb_training_log.csv`` / ``lstm_training_log.csv`` rows describing the
   runs that produced the canonical models;
3. reruns every producer that reads the focused learned forecasts and splices
   focused rows into mixed-tier files;
4. checks invariants: files outside the declared learned-forecast consumers
   are byte-identical before/after; ARIMA rows and unaffected LSTM rows of the
   focused replay/accuracy tables are unchanged; non-focused statistical
   families are unchanged;
5. independently replays B6/B7 for 20 services x {XGBoost, LSTM} x 3 budgets
   and compares overload counts exactly and costs to rounding;
6. checks that the MS_25320 held-out replays do not depend on the eight
   corrected pre-test minutes.

    python3 audit/recompute_final_closure_downstream.py --write
    python3 audit/recompute_final_closure_downstream.py --check

``--check`` repeats steps 1, 2 (in memory, compared exactly with the
installed canonical parquet files and logs), 5 and 6, and compares the
recorded post-write hashes of all consumer outputs with the current files.
"""

