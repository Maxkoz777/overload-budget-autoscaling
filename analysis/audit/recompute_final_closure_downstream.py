# Step 4: invariants
def semantic_invariants(before_dir: Path) -> dict:
    """Rows that must not depend on the XGBoost/LSTM replacement."""
    out = {}
    a_old = pd.read_csv(before_dir / "advanced_policy_replay_per_service.csv")
    a_new = pd.read_csv(RESULTS / "advanced_policy_replay_per_service.csv")
    keep = lambda f: f[f.policy.str.startswith("arima") | (f.policy.str.startswith("lstm") & (f.msname != LSTM_SERVICE))]  # noqa: E731
    pd.testing.assert_frame_equal(keep(a_old).sort_values(["msname", "policy"]).reset_index(drop=True),
                                  keep(a_new).sort_values(["msname", "policy"]).reset_index(drop=True))
    out["advanced_replay_arima_and_unaffected_lstm_rows_unchanged"] = True
    f_old = pd.read_csv(before_dir / "advanced_forecasting_comparison.csv")
    f_new = pd.read_csv(RESULTS / "advanced_forecasting_comparison.csv")
    keepf = lambda f: f[(f.model == "arima") | ((f.model == "lstm") & (f.msname != LSTM_SERVICE))]  # noqa: E731
    pd.testing.assert_frame_equal(keepf(f_old).sort_values(["msname", "model"]).reset_index(drop=True),
                                  keepf(f_new).sort_values(["msname", "model"]).reset_index(drop=True))
    out["accuracy_arima_and_unaffected_lstm_rows_unchanged"] = True
    s_old = pd.read_csv(before_dir / "paired_effect_intervals.csv")
    s_new = pd.read_csv(PAPER / "audit/statistical_results/paired_effect_intervals.csv")
    nf = lambda f: f[~f.family.str.startswith("focused")].reset_index(drop=True)  # noqa: E731
    pd.testing.assert_frame_equal(nf(s_old), nf(s_new))
    out["non_focused_statistical_families_unchanged"] = True
    return out


# Steps 5-6: replays
def independent_replay() -> dict:
    """Recompute B6/B7 rows from the canonical forecasts and compare with the CSV."""
    cwd = os.getcwd()
    os.chdir(RESEARCH)
    sys.path.insert(0, str(EXP / "src"))
    import run_advanced_policy_replay as adv  # noqa: E402
    from metrics import evaluate_capacity  # noqa: E402
    from risk_policy import RiskPolicyConfig  # noqa: E402
    split = json.loads((EXP / "data/splits/split_definition.json").read_text())
    smap = {s["name"]: s for s in split["splits"]}
    stored = pd.read_csv(RESULTS / "advanced_policy_replay_per_service.csv").set_index(["msname", "policy"])
    baseline = pd.read_csv(RESULTS / "baseline_replay_per_service.csv")
    observed = baseline[baseline.policy == "observed_capacity"].set_index("msname").c_total
    checked, worst = 0, 0.0
    for model in ("xgb", "lstm"):
        fc = pd.read_parquet(RESULTS / f"{model}_forecasts.parquet")
        for service in runs.focused_services():
            frame = pd.read_parquet(EXP / "data/service_timeseries" / f"{service}.parquet").sort_values("timestamp")
            history = pd.concat([adv.split_frame(frame, smap["train"]), adv.split_frame(frame, smap["calibration"])],
                                ignore_index=True)
            test = adv.split_frame(frame, smap["test"])
            demand = test.cpu_sum.to_numpy(float)
            forecast = fc[fc.msname == service].sort_values("timestamp").forecast.to_numpy(float)
            for delta in adv.DELTA_VALUES:
                for guard, label in ((False, "margin_only"), (True, "guardrail")):
                    config = RiskPolicyConfig(delta=delta, window=adv.WINDOW, alpha=adv.ALPHA, mu=adv.MU,
                                              rho=adv.RHO, guardrail_h=adv.GUARDRAIL_H,
                                              guardrail_gamma=adv.GUARDRAIL_GAMMA,
                                              use_margin=True, use_guardrail=guard)
                    capacity = adv.simulate_policy_with_external_forecast(history, test, forecast, config)
                    res = evaluate_capacity(service=service, policy="x", timestamps=test["timestamp"],
                                            demand=demand, capacity=capacity, mu=adv.MU,
                                            cost_config=adv.COST_CONFIG)
                    row = stored.loc[(service, f"{model}_conformal_{label}_d{delta}")]
                    assert int(res["overload_count"]) == int(row.overload_count), (service, model, delta, label)
                    rel_cost = res["c_total"] / observed[service]
                    diff = abs(rel_cost - row.relative_cost_vs_observed)
                    assert np.isclose(rel_cost, row.relative_cost_vs_observed, rtol=1e-9, atol=1e-12)
                    assert np.isclose(res["c_total"], row.c_total, rtol=1e-9, atol=1e-6)
                    worst = max(worst, float(diff))
                    checked += 1
    os.chdir(cwd)
    assert checked == 240, checked
    return {"rows_checked": checked, "overload_counts_exact": True, "max_abs_relative_cost_diff": worst}


def replay_input_invariance() -> dict:
    cwd = os.getcwd()
    os.chdir(RESEARCH)
    sys.path.insert(0, str(EXP / "src"))
    import exp_core  # noqa: E402
    import run_advanced_policy_replay as adv  # noqa: E402
    from risk_policy import RiskPolicyConfig  # noqa: E402
    split = json.loads((EXP / "data/splits/split_definition.json").read_text())
    hist_old, test_old = exp_core.load_service_data(HISTORICAL_INPUT, split)
    hist_new, test_new = exp_core.load_service_data(PAST_ONLY, split)
    pd.testing.assert_frame_equal(test_old.reset_index(drop=True), test_new.reset_index(drop=True))
    out = {}
    for model in ("persistence", "xgb", "lstm"):
        forecast = None
        if model != "persistence":
            frame = pd.read_parquet(RESULTS / f"{model}_forecasts.parquet")
            forecast = frame[frame.msname == LSTM_SERVICE].sort_values("timestamp").forecast.to_numpy(float)
        for delta in (0.10, 0.05, 0.01):
            a = exp_core.simulate_policy(hist_old, test_old, forecast, delta=delta, W=240,
                                         use_margin=True, use_guardrail=True)
            b = exp_core.simulate_policy(hist_new, test_new, forecast, delta=delta, W=240,
                                         use_margin=True, use_guardrail=True)
            out[f"{model}_d{delta}"] = all(np.array_equal(np.asarray(a[k]), np.asarray(b[k]))
                                           for k in a if not isinstance(a[k], dict))
        if model != "persistence":
            for delta in adv.DELTA_VALUES:
                for guard in (False, True):
                    config = RiskPolicyConfig(delta=delta, window=adv.WINDOW, alpha=adv.ALPHA, mu=adv.MU,
                                              rho=adv.RHO, guardrail_h=adv.GUARDRAIL_H,
                                              guardrail_gamma=adv.GUARDRAIL_GAMMA,
                                              use_margin=True, use_guardrail=guard)
                    a = adv.simulate_policy_with_external_forecast(hist_old, test_old, forecast, config)
                    b = adv.simulate_policy_with_external_forecast(hist_new, test_new, forecast, config)
                    out[f"advanced_{model}_d{delta}_guard{guard}"] = bool(np.array_equal(a, b))
    os.chdir(cwd)
    assert all(out.values()), out
    return out


