def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def rel(path: Path) -> str:
    return os.path.relpath(path, RESEARCH)


def snapshot() -> dict[str, str]:
    out = {}
    for root in WATCHED_ROOTS:
        for path in sorted(root.rglob("*")):
            if not path.is_file() or path.name == ".DS_Store" or "__pycache__" in path.parts:
                continue
            if RUNS in path.parents:        # the new runs and this script's outputs
                continue
            out[rel(path)] = sha256(path)
    return out


def allowed(name: str) -> bool:
    return name in ALLOWED_CHANGES or name.startswith(ALLOWED_PREFIXES)


# Steps 1-2: runs and canonical forecasts
def verify_runs() -> None:
    services = runs.focused_services()
    bad = [s for s in services if not runs.verify_run("xgb", s)]
    if not runs.verify_run("lstm", LSTM_SERVICE):
        bad.append(f"lstm:{LSTM_SERVICE}")
    if bad:
        raise SystemExit(f"final-closure runs missing or not verified: {bad}")


def run_forecasts(model: str, service: str) -> pd.DataFrame:
    return pd.read_parquet(RUNS / model / service / "forecasts.parquet").sort_values("timestamp")


def pre_closure(name: str) -> Path:
    """The canonical file as it was before this closure step."""
    saved = SUPERSEDED / name
    return saved if saved.exists() else RESULTS / name


def expected_forecasts(model: str) -> pd.DataFrame:
    old = pd.read_parquet(pre_closure(f"{model}_forecasts.parquet"))
    services = runs.focused_services()
    assert sorted(old.msname.unique()) == services and len(old) == 20 * 4320
    replace = services if model == "xgb" else [LSTM_SERVICE]
    parts = [old[~old.msname.isin(replace)]]
    for service in replace:
        fresh = run_forecasts(model, service)
        before = old[old.msname == service].sort_values("timestamp")
        assert np.array_equal(before.timestamp.to_numpy(), fresh.timestamp.to_numpy()), service
        parts.append(fresh[old.columns].astype(old.dtypes.to_dict()))
    new = pd.concat(parts, ignore_index=True)
    new = new.sort_values(["msname", "timestamp"], kind="stable").reset_index(drop=True)
    kept = old[~old.msname.isin(replace)].sort_values(["msname", "timestamp"]).reset_index(drop=True)
    pd.testing.assert_frame_equal(kept, new[~new.msname.isin(replace)].reset_index(drop=True), check_exact=True)
    if model == "lstm" and (ROUND2_SUPERSEDED / "lstm_forecasts.parquet").exists():
        # Project history only: the 19 untouched LSTM services are also identical to the
        # original run. Skipped in a fresh reproduction, where that file does not exist.
        original = pd.read_parquet(ROUND2_SUPERSEDED / "lstm_forecasts.parquet")
        original = original[original.msname != LSTM_SERVICE].sort_values(["msname", "timestamp"]).reset_index(drop=True)
        pd.testing.assert_frame_equal(original, kept, check_exact=True)
    assert new.msname.nunique() == 20 and len(new) == 20 * 4320
    assert new.groupby("msname").timestamp.nunique().eq(4320).all()
    return new


def expected_log(model: str) -> pd.DataFrame:
    old = pd.read_csv(pre_closure(f"{model}_training_log.csv"))
    replace = runs.focused_services() if model == "xgb" else [LSTM_SERVICE]
    rows = []
    for _, row in old.iterrows():
        if row.msname in replace:
            fresh = pd.read_csv(RUNS / model / row.msname / "training_log_row.csv").iloc[0]
            rows.append({c: fresh[c] for c in old.columns})
        else:
            rows.append(row.to_dict())
    return pd.DataFrame(rows, columns=old.columns)


def install(write: bool) -> dict:
    report = {}
    for model in ("xgb", "lstm"):
        fc = expected_forecasts(model)
        lg = expected_log(model)
        canonical_fc = RESULTS / f"{model}_forecasts.parquet"
        canonical_lg = RESULTS / f"{model}_training_log.csv"
        if write:
            SUPERSEDED.mkdir(parents=True, exist_ok=True)
            for src in (canonical_fc, canonical_lg):
                if not (SUPERSEDED / src.name).exists():
                    shutil.copy2(src, SUPERSEDED / src.name)
            fc.to_parquet(canonical_fc, index=False)
            lg.to_csv(canonical_lg, index=False)
        else:
            pd.testing.assert_frame_equal(pd.read_parquet(canonical_fc), fc, check_exact=True)
            # Logs are CSV text.  pandas' default C float parser is not correctly
            # rounded, so the same text can parse to doubles one ulp apart on
            # different platforms; floats are therefore compared to 1e-12
            # (relative), everything else exactly.  Byte identity of the stored
            # log is enforced separately by the post-write hashes and manifest.
            stored = pd.read_csv(canonical_lg)
            fresh = pd.read_csv(io.StringIO(lg.to_csv(index=False)))
            assert list(stored.columns) == list(fresh.columns) and len(stored) == len(fresh), model
            for column in stored.columns:
                if pd.api.types.is_float_dtype(stored[column]):
                    assert np.allclose(stored[column], fresh[column], rtol=1e-12, atol=0, equal_nan=True), column
                else:
                    assert stored[column].astype(str).tolist() == fresh[column].astype(str).tolist(), column
        report[model] = {"services_replaced": 20 if model == "xgb" else 1, "rows": int(len(fc))}
    # The superseded copies must match the canonical hashes recorded in ROUND2_SUMMARY.
    if ROUND2_SUMMARY.exists() and SUPERSEDED.exists():
        r2 = json.loads(ROUND2_SUMMARY.read_text())["canonical_forecasts_sha256"]
        for model in ("xgb", "lstm"):
            assert sha256(SUPERSEDED / f"{model}_forecasts.parquet") == r2[model], model
    return report


# Step 3: producers
def run(cmd: list[str], log: Path) -> None:
    with open(log, "w") as handle:
        proc = subprocess.run(cmd, cwd=RESEARCH, stdout=handle, stderr=subprocess.STDOUT)
    if proc.returncode != 0:
        raise SystemExit(f"command failed ({proc.returncode}): {' '.join(cmd)}; see {log}")


